    function step(t) {
      if (!start) start = t;
      var p = Math.min((t - start) / 1800, 1);
      el.textContent = Math.floor(target * (1 - Math.pow(1 - p, 3))) + (p === 1 ? suffix : "");
      if (p < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
